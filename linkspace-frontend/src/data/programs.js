export const PROGRAMS = CATEGORIES.flatMap((category) =>
  category.videos.map((video) => ({
    ...video,
    category: category.slug,
    defaultLayout: category.defaultLayout,
  })),
);

export function findProgram(slug) {
  return PROGRAMS.find((item) => item.slug === slug) ?? null;
}

export function videosForTime(slug) {
  return PROGRAMS.filter((item) => item.times?.includes(slug));
}

export function videosForFocus(slug) {
  return PROGRAMS.filter((item) => item.focuses?.includes(slug));
}

export function suggestedTimeSlug(date = new Date()) {
  const hour = date.getHours();
  if (hour < 11) return "morning";
  if (hour < 17) return "midday";
  return "evening";
}

export function categoryName(category, lang, t) {
  if (category.nameKey) return t(category.nameKey);
  return lang === "zh" ? category.nameZh : category.nameEn;
}

